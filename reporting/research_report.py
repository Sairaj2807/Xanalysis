def walk_forward_report(run: str, preds: pd.DataFrame, inc: pd.DataFrame) -> str:
    rows = []
    for (fs, f), g in preds[(preds.model == "ridge") & (preds.horizon == 1)].groupby(["feature_set", "fold"]):
        rows.append({"feature_set": fs, "fold": f, "start": g.ts.min().date(), "end": g.ts.max().date(),
                     "rmse": float(np.sqrt(((g.y_true - g.y_pred) ** 2).mean())), "n": len(g)})
    w = pd.DataFrame(rows).pivot_table(index=["fold", "start", "end"], columns="feature_set", values="rmse").reset_index()
    cfg = ("expanding window; train_min=500; test_len=60; embargo=1 bar; validation tail 120 obs inside each training window; "
           "purging: training samples whose h-day target window reaches the test block (plus embargo) are removed")
    return "\n".join([
        "# Walk-Forward Validation Report", "", HEADER.format(runs=run), "",
        f"**Design:** {cfg}.", "", f"**Folds:** {preds.fold.nunique()}; test period {preds.ts.min().date()} .. {preds.ts.max().date()}; "
        f"observations per cell {int(inc.n.iloc[0])}.", "",
        "## RMSE by fold (ridge, n+1)", "", md_table(w, ".5f"), "",
        "## Folds in which price+sentiment beat price-only (squared error)", "",
        md_table(inc.pivot_table(index="model", columns="horizon", values="folds_combined_better").reset_index(), ".0f"), "",
        f"(of {int(inc.folds.iloc[0])} folds per cell). A genuine, stable effect would win in a clear majority of folds across horizons.", ""])


def importance_report(run: str, imp: pd.DataFrame, shap_tables: dict[int, pd.DataFrame]) -> str:
    g = imp.groupby(["model", "horizon", "group"])["mean_importance"].sum().reset_index()
    lines = ["# Feature Importance Report", "", HEADER.format(runs=run), "",
             "Permutation importance is measured out-of-sample on each walk-forward test block (increase in MSE when a feature is shuffled). "
             "Group sums are indicative only: correlated features share information.", "",
             "## Importance by feature family (px = price, sn = sentiment, ix = interactions)", "", md_table(g, ".3e"), "",
             "## Top features per model/horizon", ""]
    for (m, h), s in imp.groupby(["model", "horizon"]):
        t = s.sort_values("mean_importance", ascending=False).head(8)[["feature", "mean_importance", "frac_folds_positive"]]
        lines += [f"### {m}, n+{h}", "", md_table(t, ".3e"), ""]
    for h, t in shap_tables.items():
        lines += [f"## SHAP mean |value| (LightGBM, final fold, n+{h})", "", md_table(t.head(12), ".3e"), ""]
    lines += ["Importance values near zero or negative mean shuffling the feature did not hurt out-of-sample accuracy.", ""]
    return "\n".join(lines)
