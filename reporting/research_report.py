def md_table(df: pd.DataFrame, floatfmt: str = ".4f") -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(f"{v:{floatfmt}}" if isinstance(v, (float, np.floating)) and not pd.isna(v)
                                      else ("" if (isinstance(v, float) and pd.isna(v)) else str(v)) for v in r) + " |")
    return "\n".join(out)


def comparison_table(metrics: pd.DataFrame, model: str | None = None) -> pd.DataFrame:
    """Spec section 12 table: Persistence / Price-only / Sentiment-only / Combined x horizon."""
    z = metrics[metrics.model == "zero_return"].set_index("horizon")
    rows = []
    for h in sorted(metrics.horizon.unique()):
        p = z.loc[h]
        rows.append({"Model": "Persistence", "Horizon": f"n+{h}", "MAE": p.MAE, "RMSE": p.RMSE,
                     "Dir. acc.*": np.nan, "IC": np.nan, "OOS R2": 0.0})
        for fs, name in (("A_price", "Price-only"), ("B_sentiment", "Sentiment-only"), ("C_combined", "Combined")):
            g = metrics[(metrics.feature_set == fs) & (metrics.horizon == h)]
            if model:
                g = g[g.model == model]
            if g.empty:
                continue
            m = g[["MAE", "RMSE", "directional_accuracy", "IC", "R2_oos"]].mean()
            rows.append({"Model": name + (f" ({model})" if model else " (mean of models)"), "Horizon": f"n+{h}", "MAE": m.MAE,
                         "RMSE": m.RMSE, "Dir. acc.*": m.directional_accuracy, "IC": m.IC, "OOS R2": m.R2_oos})
    return pd.DataFrame(rows)


