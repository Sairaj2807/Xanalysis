"""MON-001 applied to the AAPL study: data completeness, volume anomalies, feature/sentiment/prediction drift,
forecast-error degradation and the retrain decision. Writes docs/reports/data_quality/<label>_monitoring_report.md."""
from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from config.settings import ROOT, load_settings  # noqa: E402
from monitoring.data_monitor import missing_periods, volume_anomalies  # noqa: E402
from monitoring.drift_monitor import drift_report  # noqa: E402
from monitoring.model_monitor import RetrainPolicy, rolling_degradation, should_retrain  # noqa: E402
from reporting.research_report import md_table  # noqa: E402
from reporting.run_index import latest_run  # noqa: E402


def main(label: str | None = None) -> None:
    label = label or date.today().isoformat()
    a = load_settings().asset
    table = pd.read_parquet(ROOT / "data" / "model_ready" / f"model_table_{a.symbol}_primary.parquet")
    agg = pd.read_parquet(ROOT / "data" / "aggregated" / f"sentiment_daily_{a.symbol}_primary.parquet")
    sets = json.loads((ROOT / "data" / "model_ready" / "feature_sets.json").read_text())
    n = len(table)
    ref, rec = table.iloc[: int(0.6 * n)], table.iloc[-int(0.2 * n):]
    cols = [c for c in sets["C_combined"] if table[c].notna().sum() > 50]
    drift = drift_report(ref, rec, cols)
    sent_cols = ["sn_sent_mean", "sn_post_count", "sn_pos_ratio", "sn_neg_ratio", "sn_sent_confidence"]
    miss = missing_periods(agg[agg.trading_day.between(table.index[0], table.index[-1])], table.index, min_posts=20)
    vol = volume_anomalies(agg.set_index("trading_day")["post_count"].loc[table.index[0]:table.index[-1]])
    preds = pd.read_parquet(latest_run("primary") / "oos_predictions.parquet")
    g = preds[(preds.model == "ridge") & (preds.feature_set == "C_combined") & (preds.horizon == 1)].sort_values("ts")
    err = pd.Series((g.y_true - g.y_pred).to_numpy(), index=g.ts)
    deg = rolling_degradation(err, recent=120)
    psi_max = float(drift.psi.max())
    flag, why = should_retrain(RetrainPolicy(), model_age_days=0, degradation_ratio=deg["ratio"], max_feature_psi=psi_max)
    lines = [f"# Monitoring Report ({label})", "", f"> AUTO-GENERATED by scripts/run_monitoring.py. Reference window: first 60% ({ref.index[0].date()}..{ref.index[-1].date()}); recent window: last 20% ({rec.index[0].date()}..{rec.index[-1].date()}).", "",
             "## Data completeness", "", f"- Trading days with fewer than 20 filtered posts or missing: **{len(miss)}** of {n}.",
             f"- Post-volume anomalies (|robust z| > 3): **{len(vol)}** days.", "",
             "## Feature drift (PSI; >=0.10 warn, >=0.25 alert)", "",
             f"- Alerts: {int((drift.status == 'alert').sum())}; warnings: {int((drift.status == 'warn').sum())}; of {len(drift)} features.", "",
             md_table(drift.head(12), ".3f"), "", "## Sentiment-distribution drift", "",
             md_table(drift[drift.feature.isin(sent_cols)], ".3f"), "",
             "## Forecast-error degradation (ridge, price+sentiment, n+1)", "",
             f"- Recent-120-day RMSE / earlier RMSE = **{deg['ratio']:.2f}** (recent {deg['recent_rmse']:.5f} vs history {deg['history_rmse']:.5f}).", "",
             "## Retrain decision", "", f"- Retrain recommended: **{flag}**. Reasons: {why or 'none'}.",
             "- A retrained model would only be promoted if it beats the incumbent with a significant one-sided Diebold-Mariano test (`monitoring.model_monitor.promote_candidate`).", ""]
    out = ROOT / "docs" / "reports" / "data_quality"
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{label}_monitoring_report.md").write_text("\n".join(lines), encoding="utf-8")
    print("alerts:", int((drift.status == "alert").sum()), "warn:", int((drift.status == "warn").sum()), "| missing/thin days:", len(miss),
          "| vol anomalies:", len(vol), "| degradation ratio: %.2f" % deg["ratio"], "| retrain:", flag, why)
    print(drift.head(6).round(3).to_string(index=False))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else None)
