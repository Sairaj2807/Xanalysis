"""Generate docs/engineering/CODEBASE_MAP.md from the actual source tree (AST inventory; fully automatic).

Factual inventory only: modules, public classes/functions, line counts, tests per file.
Status and interpretation live in IMPLEMENTATION_TRACKER.md (written by humans/agents, never overwritten here).
"""
from __future__ import annotations

import ast
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP = {".venv", "data", "docs", "artifacts", ".git", "__pycache__", "logs", ".pytest_cache", "notebooks"}


def py_files() -> list[Path]:
    out = []
    for p in sorted(ROOT.rglob("*.py")):
        if any(part in SKIP for part in p.relative_to(ROOT).parts):
            continue
        out.append(p)
    return out


def describe(p: Path) -> tuple[str, list[str], int]:
    src = p.read_text(encoding="utf-8")
    tree = ast.parse(src)
    doc = (ast.get_docstring(tree) or "").strip().splitlines()
    summary = doc[0] if doc else ""
    names = []
    for n in tree.body:
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and not n.name.startswith("_"):
            names.append(f"{n.name}()")
        elif isinstance(n, ast.ClassDef) and not n.name.startswith("_"):
            names.append(f"class {n.name}")
    return summary, names, len(src.splitlines())


def test_counts(p: Path) -> int:
    tree = ast.parse(p.read_text(encoding="utf-8"))
    return sum(isinstance(n, ast.FunctionDef) and n.name.startswith("test_") for n in tree.body)


def main() -> None:
    lines = ["# Codebase Map", "",
             f"> AUTO-GENERATED by `scripts/generate_codebase_map.py` on {date.today().isoformat()}. Do not edit by hand.",
             "> Factual inventory only. Status/verification is in [IMPLEMENTATION_TRACKER.md](IMPLEMENTATION_TRACKER.md).", ""]
    groups: dict[str, list[Path]] = {}
    for p in py_files():
        rel = p.relative_to(ROOT)
        groups.setdefault(rel.parts[0] if len(rel.parts) > 1 else "(root)", []).append(p)
    total = 0
    for g, files in groups.items():
        files = [f for f in files if f.name != "__init__.py" or f.stat().st_size > 0]
        if not files:
            continue
        lines += [f"## {g}/", "", "| File | Lines | Purpose (module docstring) | Public API |", "|---|---:|---|---|"]
        for p in files:
            summary, names, n = describe(p)
            total += n
            n_tests = test_counts(p) if g == "tests" else 0
            extra = f" ({n_tests} tests)" if n_tests else ""
            lines.append(f"| `{p.relative_to(ROOT).as_posix()}` | {n} | {summary}{extra} | {', '.join(names[:8])}{' ...' if len(names) > 8 else ''} |")
        lines.append("")
    empty = sorted({p.parent.relative_to(ROOT).as_posix() for p in py_files() if p.name == "__init__.py" and p.stat().st_size == 0})
    stub_dirs = [d for d in empty if not any(f.parent.relative_to(ROOT).as_posix() == d and f.name != "__init__.py" for f in py_files())]
    lines += ["## Packages containing only an empty `__init__.py` (no implementation)", ""]
    lines += [f"- `{d}/`" for d in stub_dirs] or ["- none"]
    lines += ["", f"Total Python lines (excluding empty files): {total}", ""]
    out = ROOT / "docs" / "engineering" / "CODEBASE_MAP.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} ({total} lines of code)")


if __name__ == "__main__":
    main()
